fun siteByKey(key: String): Site? = SITES.firstOrNull { it.key == key }

fun siteLabel(key: String): String =
    siteByKey(key)?.name ?: if (key.startsWith("custom:")) key.substringAfter(':') else key

fun siteIconDomain(key: String): String =
    siteByKey(key)?.iconDomain ?: if (key.startsWith("custom:")) key.substringAfter(':') else ""

fun hostOf(url: String): String = try {
    Uri.parse(url.trim()).host?.lowercase() ?: ""
} catch (e: Exception) {
    ""
}

fun baseDomain(host: String): String {
    val parts = host.split('.').filter { it.isNotEmpty() }
    return if (parts.size >= 2) parts.takeLast(2).joinToString(".") else host
}

data class Cookie(
    val domain: String,
    val path: String,
    val secure: Boolean,
    val httpOnly: Boolean,
    val expires: Long,
    val name: String,
    val value: String,
)

/** Забираем cookies из WebView по списку адресов. Android не даёт перечислить все cookies — читаем по известным доменам. */
fun collectCookies(urls: List<String>): List<Cookie> {
    val manager = CookieManager.getInstance()
    val expires = System.currentTimeMillis() / 1000 + 180L * 24 * 3600
    val found = LinkedHashMap<String, Cookie>()
    for (url in urls) {
        val raw = manager.getCookie(url) ?: continue
        val domain = "." + baseDomain(hostOf(url))
        for (part in raw.split(";")) {
            val i = part.indexOf('=')
            if (i <= 0) continue
            val name = part.substring(0, i).trim()
            val value = part.substring(i + 1).trim()
            if (name.isEmpty()) continue
            found["$domain|$name"] = Cookie(domain, "/", true, false, expires, name, value)
        }
    }
    return found.values.toList()
}

// ------------------------------------------------------------------ cookies.txt (Netscape)
fun cookiesToNetscape(cookies: List<Cookie>): String {
    val sb = StringBuilder("# Netscape HTTP Cookie File\n# Generated by Zephyrus\n\n")
    for (c in cookies) {
        if (c.domain.isEmpty()) continue
        val prefix = if (c.httpOnly) "#HttpOnly_" else ""
        sb.append(prefix).append(c.domain).append('\t')
            .append(if (c.domain.startsWith(".")) "TRUE" else "FALSE").append('\t')
            .append(c.path.ifEmpty { "/" }).append('\t')
            .append(if (c.secure) "TRUE" else "FALSE").append('\t')
            .append(c.expires).append('\t')
            .append(c.name).append('\t')
            .append(c.value).append('\n')
    }
    return sb.toString()
}

fun parseNetscape(text: String): List<Cookie> {
    val out = ArrayList<Cookie>()
    for (raw in text.lines()) {
        var line = raw.trimEnd('\r', '\n')
        if (line.isBlank()) continue
        var httpOnly = false
        if (line.startsWith("#HttpOnly_")) {
            httpOnly = true
            line = line.removePrefix("#HttpOnly_")
        } else if (line.startsWith("#")) {
            continue
        }
        val p = line.split('\t')
        if (p.size != 7) continue
        out.add(
            Cookie(
                domain = p[0], path = p[2].ifEmpty { "/" }, secure = p[3].equals("TRUE", true),
                httpOnly = httpOnly, expires = p[4].toDoubleOrNull()?.toLong() ?: 0L, name = p[5], value = p[6],
            )
        )
    }
    return out
}

/** Зашифрованные cookie-профили. Метаданные — в SQLite, сами cookies — в файлах, зашифрованных Android Keystore. */
class SessionStore(context: Context, private val db: Database) {
    private val dir = File(context.filesDir, "profiles").apply { mkdirs() }

    private fun file(id: String) = File(dir, "$id.zcp")

    fun add(site: String, name: String, cookies: List<Cookie>, hosts: List<String>? = null): String {
        val id = UUID.randomUUID().toString().replace("-", "")
        val arr = JSONArray()
        for (c in cookies) {
            arr.put(
                JSONObject().put("d", c.domain).put("p", c.path).put("s", c.secure).put("h", c.httpOnly)
                    .put("e", c.expires).put("n", c.name).put("v", c.value)
            )
        }
        file(id).writeBytes(Vault.encrypt(arr.toString().toByteArray(Charsets.UTF_8)))
        val resolved = hosts ?: siteByKey(site)?.domains ?: listOf(site.substringAfter(':', ""))
        db.insertProfile(id, site, name, resolved.filter { it.isNotEmpty() }, cookies.size)
        return id
    }

    fun load(id: String): List<Cookie> {
        val json = String(Vault.decrypt(file(id).readBytes()), Charsets.UTF_8)
        val arr = JSONArray(json)
        return (0 until arr.length()).map {
            val o = arr.getJSONObject(it)
            Cookie(o.getString("d"), o.getString("p"), o.getBoolean("s"), o.getBoolean("h"),
                o.getLong("e"), o.getString("n"), o.getString("v"))
        }
    }

    fun importNetscape(site: String, name: String, text: String, hosts: List<String>? = null): String {
        val cookies = parseNetscape(text)
        require(cookies.isNotEmpty()) { "В файле не найдено ни одной cookie в формате Netscape" }
        val resolved = hosts ?: if (siteByKey(site) == null) cookies.map { baseDomain(it.domain.trimStart('.')) } else null
        return add(site, name, cookies, resolved)
    }

    /** Активный профиль, чьи домены подходят к ссылке. */
    fun profileForUrl(url: String): ProfileRow? {
        val host = hostOf(url)
        if (host.isEmpty()) return null
        return db.profiles.value.firstOrNull { p ->
            p.active && p.hosts.split(',').filter { it.isNotEmpty() }.any { host == it || host.endsWith(".$it") }
        }
    }

    /** Расшифровать профиль во временный cookies.txt для yt-dlp (удаляется после загрузки). */
    fun exportTemp(id: String, target: File): File {
        target.parentFile?.mkdirs()
        target.writeText(cookiesToNetscape(load(id)), Charsets.UTF_8)
        return target
    }

    fun rename(id: String, name: String) = db.renameProfile(id, name)

    fun setActive(id: String) = db.setActiveProfile(id)

    fun delete(id: String) {
        db.deleteProfile(id)
        file(id).delete()
    }
}
